export type VendorRegion = 'USA Domestic' | 'Canada';

export interface Vendor {
  slug: string;
  name: string;
  init: string;
  domain: string;
  country: string;
  region: VendorRegion;
  score: number;
  reviews: number;
  purity: number;
  shipping: number;
  support: number;
  verified: boolean;
  publicCoa: boolean;
  thirdPartyLab: boolean;
  qrVerify: boolean;
  compounds: string[];
  registered: string;
  ssl: boolean;
  responseRate: number;
  avgShipDays: number;
  about?: string;
  aiSummary?: string;
  aiSummaryCount?: number;
  /** Real logo URL slot. Leave undefined to show the monogram placeholder. */
  logo?: string;
  logoDark?: boolean;
  /** Optional custom tile background (tailwind classes) shown behind the logo image. */
  logoBg?: string;
  /** Placeholder tile gradient (only used while `logo` is empty). */
  brand?: string;
  planTier?: 'free' | 'paid';
  /** Curated default-directory placement (1 = top). Optional - only set for hand-picked leaders. */
  rank?: number;
  hidden?: boolean;
  /** Paid featured placement. Vendor appears in the sponsored banner above the grid. */
  sponsored?: boolean;
}

type Flag = 'coa' | 'lab' | 'qr';

interface VendorSeed {
  slug: string;
  name: string;
  init: string;
  domain: string;
  country: string;
  region: VendorRegion;
  score: number;
  reviews: number;
  ship: number;
  compounds: string[];
  registered: string;
  flags?: Flag[];
  response?: number;
  plan?: 'free' | 'paid';
  verified?: boolean;
  about?: string;
  aiSummary?: string;
  aiSummaryCount?: number;
  logo?: string;
  logoDark?: boolean;
  logoBg?: string;
  rank?: number;
  hidden?: boolean;
  sponsored?: boolean;
}

// Distinct monogram tile palette so a wall of placeholder logos still reads like
// a set of separate brands (no blue / purple, per the site's design rules).
const brandPalette = [
  'from-teal-500 to-emerald-500',
  'from-emerald-500 to-lime-500',
  'from-amber-500 to-orange-500',
  'from-rose-500 to-orange-400',
  'from-slate-700 to-slate-900',
  'from-teal-600 to-cyan-600',
  'from-orange-500 to-amber-600',
  'from-lime-500 to-emerald-600',
  'from-rose-500 to-pink-400',
  'from-cyan-600 to-teal-500',
];

const DEFAULT_FLAGS: Flag[] = ['coa', 'lab', 'qr'];

function build(seed: VendorSeed, index: number): Vendor {
  const flags = new Set(seed.flags ?? DEFAULT_FLAGS);
  const score = seed.score;
  // Sub-scores fan out just below the headline score. Zero means no data yet, never fabricate.
  const purity = score === 0 ? 0 : Math.min(5, Number((score + 0.05).toFixed(2)));
  const shipping = score === 0 ? 0 : Number(Math.max(3.6, Math.min(5, score - 0.05)).toFixed(2));
  const support = score === 0 ? 0 : Number(Math.max(3.5, Math.min(5, score - 0.12)).toFixed(2));

  return {
    slug: seed.slug,
    name: seed.name,
    init: seed.init,
    domain: seed.domain,
    country: seed.country,
    region: seed.region,
    score,
    reviews: seed.reviews,
    purity,
    shipping,
    support,
    verified: seed.verified ?? true,
    publicCoa: flags.has('coa'),
    thirdPartyLab: flags.has('lab'),
    qrVerify: flags.has('qr'),
    compounds: seed.compounds,
    registered: seed.registered,
    ssl: true,
    responseRate: seed.response ?? Math.round(Math.max(72, Math.min(97, 82 + (score - 4) * 16))),
    avgShipDays: seed.ship,
    about: seed.about,
    aiSummary: seed.aiSummary,
    aiSummaryCount: seed.aiSummaryCount,
    logo: seed.logo,
    logoDark: seed.logoDark,
    logoBg: seed.logoBg,
    brand: brandPalette[index % brandPalette.length],
    planTier: seed.plan,
    rank: seed.rank,
    hidden: seed.hidden,
    sponsored: seed.sponsored,
  };
}

